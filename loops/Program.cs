using System;

namespace loops
{
    class loops
    {
        static void Main(string[] args)
        {
            // For loop example

            for (int i = 1; i <= 10; i++)
            {
                Console.WriteLine(i);
            }



            for (int i = 2; i <= 20; i += 2)
            {
                Console.WriteLine(i);
            }


        }
    }
}
